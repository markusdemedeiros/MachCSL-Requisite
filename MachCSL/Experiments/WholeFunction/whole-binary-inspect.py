#!/usr/bin/env python3
"""Propose whole-function certificates from the project's kernel image.

This is an UNTRUSTED generator. It emits addresses, never instruction ASTs.
Lean checks actual Sail decoding in M/S modes, contiguous byte coverage,
and all local control-flow edges. The interval is delimited by named image
symbols; it is deliberately not a claim about ELF st_size metadata.
Comments/objdump mnemonics only propose regression expectations, which are
then independently checked against the decoder-derived flow in Lean.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
source = (ROOT / "Xv6/KernelImage.lean").read_text()
symbols = {n: int(a, 16) for n, a in re.findall(
    r'def «([^»]+)» : Nat := (0x[0-9a-f]+)', source)}
records = [(int(a, 16), int(w), asm.strip()) for asm, a, w in re.findall(
    r'  -- ([^\n]*)\n  ⟨(0x[0-9a-f]+), ([24]), 0x[0-9a-f]+⟩', source)]

output = ['-- Generated by whole-binary-inspect.py; all evidence is kernel checked.',
          'import Experiments.WholeFunction.Binary', '',
          'namespace Xv6.WholeFunction.Binary', 'open MachCSL', 'noncomputable section',
          'set_option maxHeartbeats 0', '']
report = []
for name, following in [('copyout', 'copyin'), ('copyin', 'copyinstr'),
                        ('copyinstr', 'proc_mapstacks')]:
    start, end = symbols[name], symbols[following]
    rows = [(a, w, asm) for a, w, asm in records if start <= a < end]
    assert rows and rows[0][0] == start
    assert all(a + w == b for (a, w, _), (b, _, _) in zip(rows, rows[1:]))
    assert rows[-1][0] + rows[-1][1] == end
    names = []
    calls, backs, returns = [], [], []
    for a, w, asm in rows:
        row = f'{name}_{a - start:03x}'
        names.append(row)
        output.extend([
            f'def {row} : Row := rowAt {a:#x}#64 (by binary_rfl) (by binary_rfl)'])
        mnemonic = asm.split()[0]
        target = re.search(r'([0-9a-f]+) <', asm)
        if mnemonic == 'jal' and target:
            calls.append((a, int(target[1], 16), a+w))
        if mnemonic in ('j', 'beqz', 'bnez', 'beq', 'bne', 'bltu', 'bgeu', 'blt', 'bge') and target:
            dest = int(target[1], 16)
            if dest <= a:
                backs.append((a, dest))
        if mnemonic == 'ret':
            returns.append(a)
    output.extend(['', f'def {name} : Function where',
        f'  entry := KA.«{name}»', f'  finish := KA.«{following}»',
        '  rows := [' + ', '.join(names) + ']',
        '  covers := by binary_rfl', '  localEdges := by binary_rfl', ''])
    triples = ', '.join(f'({a:#x}#64, {b:#x}#64, {c:#x}#64)' for a,b,c in calls)
    pairs = ', '.join(f'({a:#x}#64, {b:#x}#64)' for a,b in backs)
    inds = ', '.join(f'({a:#x}#64, .indirect 0#12 (.Regidx 1#5) (.Regidx 0#5))' for a in returns)
    output.extend([
        f'theorem {name}_calls : {name}.calls = [{triples}] := by binary_rfl',
        f'theorem {name}_backedges : {name}.backedges = [{pairs}] := by binary_rfl',
        f'theorem {name}_returns : {name}.indirects = [{inds}] := by binary_rfl', ''])
    report.append(f'{name}: [{start:#x}, {end:#x}), {end-start} bytes, {len(rows)} instructions, '
                  f'{len(calls)} call sites, {len(backs)} backward edges, {len(returns)} returns')
output.extend(['end', 'end Xv6.WholeFunction.Binary', ''])
(ROOT / 'Experiments/WholeFunction/BinaryCopy.lean').write_text('\n'.join(output))
print('\n'.join(report))
